<p>15歳未満と65歳以上の割合は人口のうち、ひとり暮らしの割合は一般世帯のうちです。共同住宅と一戸建ての割合は、住宅に住む一般世帯のうちです。年齢や世帯の種類が不詳の人は割り振った値（不詳補完値）を使っています。</p>
